/**
 * Логическое ударение в тексте для Silero через RuVoice: слово в звёздочках (`*город*`) модель выделяет
 * интонацией (правило RuVoice «Логическое ударение», сила 1–3, по умолчанию 3).
 * Для показа на экране и для системного TTS звёздочки снимаются, иначе их могут прочитать вслух.
 */
export function stripFocusMarks(text: string) {
  return text.replace(/\*([^*\s]+)\*/g, '$1');
}
