const openQuestions = [
  'Расскажи чуть подробнее! Что тебе в этом *больше* всего нравится?',
  'Давай представим, что у тебя освободился *целый* день. Чем бы ты его занял?',
  'Мне любопытно: что тебе важнее, когда проводишь время с кем-то — общий *интерес* или *лёгкость* в общении?',
];

/**
 * Короткие словесные реакции перед вопросом. Междометия вроде «угу» и «мгм» синтез произносит как слова,
 * а не как живое поддакивание, поэтому реакции — обычные слова с понятной интонацией.
 */
const reactions = [
  'Понятно.',
  'О, интересно!',
  'Здорово!',
  'Вот как!',
  'Ага, понимаю.',
  'Слушай, классно!',
  'Хм, любопытно.',
  'Да, понимаю тебя.',
  'Ничего себе!',
  'Ясно.',
];

/** Ответ уже начинается с реакции — вторую не добавляем. */
const startsWithReaction = /^(Здорово|Интересно|Мне любопытно|Расскажи)/u;

export const mockConversationService = {
  createSession() {
    const used = new Map<readonly string[], number>();
    let lastReaction = -1;
    let turn = 0;

    const react = () => {
      // Не на каждую реплику: живой собеседник реагирует через раз и разными словами.
      turn += 1;
      if (turn % 3 === 0) return '';
      let index = Math.floor(Math.random() * reactions.length);
      if (index === lastReaction) index = (index + 1) % reactions.length;
      lastReaction = index;
      return `${reactions[index]} `;
    };

    return {
      replyTo(text: string) {
        const replies = topics.find(({ pattern }) => pattern.test(text))?.replies ?? openQuestions;
        const index = used.get(replies) ?? 0;
        used.set(replies, (index + 1) % replies.length);
        const reply = replies[index];
        return startsWithReaction.test(reply) ? reply : `${react()}${reply}`;
      },
    };
  },
};
